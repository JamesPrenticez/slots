import { Assets, Container } from "pixi.js";

import { BetData } from "../../common/models/data/BetData.js";
import { WinData } from "../../common/models/data/WinData.js";
import { createAbortableDelay } from "../../common/util/AbortableDelay.js";
import { nextFrame, nextFrameIfExceedFrameTime } from "../../common/util/index.js";
import { assetsReady } from "../../engine/assets.js";
import {
	FanfareBaseSlotApplication,
	getFanfareBaseSlotApplication
} from "../../fanfarebaseslot/FanfareBaseSlotApplication.js";
import { ViewStore } from "../../fanfarebaseslot/ViewStore.js";
import { Resizable } from "../../slot/renderer/Resizable.js";
import { CharacterArea } from "../components/layout/CharacterArea.js";
import { GameArea } from "../components/layout/GameArea.js";
import { LogoArea } from "../components/layout/LogoArea.js";
import { ScreenSafeArea } from "../components/layout/ScreenSafeArea.js";
import { SlotMachineController } from "./SlotMachineController.js";

/**
 * CoreController — the abstract base class that every game controller extends.
 *
 * Manages the full boot sequence from loading screen to playable game:
 *
 *   1. loadPreloadBundle
 *      Calls Assets.loadBundle("default") using the manifest generated by
 *      assetpack. The progress bar in the loading screen fills as files load.
 *      In production a minimum 3-second display time ensures players see
 *      the loading screen long enough to read the game name.
 *
 *   2. createGameScene (implemented by the game)
 *      The game builds its scene objects — Background, SlotMachine, WinEffect
 *      etc — using addToScene(). Each object starts hidden. A nextFrame()
 *      yield between each construction step keeps the loading screen animating
 *      smoothly even when creating expensive objects like Spine animations.
 *
 *   3. updateLayout
 *      Forces the first layout calculation so GameArea has correct dimensions
 *      before the SlotMachine is scaled and positioned with fitSlotMachine().
 *      Subsequent resize events are handled automatically via the listener
 *      registered here.
 *
 *   4. onGameReady (optional, overridden by the game)
 *      Post-scene setup — typically executes OpenGameCommand to connect
 *      to the RGS server and get initial bet/balance data.
 *
 *   5. showGameScene
 *      Makes all scene objects visible and fades out the loading screen.
 *      The player sees the game for the first time here.
 */
export abstract class CoreController extends SlotMachineController {
	private static instance?: CoreController;

	public static getInstance(): CoreController {
		if (!CoreController.instance) {
			throw new Error("CoreController not created.");
		}
		return CoreController.instance;
	}

	protected readonly screenSafeArea = new ScreenSafeArea();
	protected readonly logoArea: LogoArea;
	protected readonly gameArea: GameArea;
	protected readonly characterArea: CharacterArea;
	private readonly gameContainers: Container[] = [];
	private readonly autoRevealExclusions = new Set<Container>();
	private appInstance?: FanfareBaseSlotApplication;

	protected constructor(gameAspectRatio: number) {
		super();
		CoreController.instance = this;
		this.logoArea = new LogoArea(gameAspectRatio);
		this.gameArea = new GameArea(gameAspectRatio);
		this.characterArea = new CharacterArea(gameAspectRatio);
	}

	public onRootCreated(): void {
		this.setupGame().catch((err: unknown) => {
			const msg = err instanceof Error ? err.message : String(err);
			console.error("CoreController.setupGame failed:", err);
			this.showError("Initialisation Error", msg);
		});
	}

	private setupGlobalTapToSkip(): void {
		const { app } = getFanfareBaseSlotApplication();
		app.stage.on("pointerdown", () => this.onScreenTap());
	}
	// this function handle things we want to happen after screen tap(skip/abort)
	private onScreenTap(): void {
		if (ViewStore.getInstance().has("BigWinEffect")) {
			ViewStore.getInstance().get("BigWinEffect").skip();
		}
	}

	private async setupGame(): Promise<void> {
		this.appInstance = getFanfareBaseSlotApplication();
		const { app } = this.appInstance;

		// 1. Load assets — progress bar drives this, loader stays visible
		await this.loadPreloadBundle();

		// 1b. Wait for any web fonts requested via index.html (e.g. "Titan One")
		// to actually finish loading before any PixiJS Text using them gets
		// created. PixiJS rasterizes Text into a texture at construction time
		// and does NOT re-render it later if the font finishes loading after
		// the fact — unlike DOM/CSS text, which reflows automatically. Must
		// run before createGameScene()
		await document.fonts.ready;

		// 2. Initialise data models, currently server has only 4 as max bet, might need to modify based on server response
		BetData.getInstance().init(100, [20, 40, 60, 100, 200, 400]);
		WinData.getInstance().setViewWin(0);

		// 3. Add layout helpers to stage
		app.stage.addChild(this.screenSafeArea, this.logoArea, this.gameArea, this.characterArea);

		this.setupGlobalTapToSkip();

		// 4. Build scene — nextFrame forest keeps loading screen smooth
		await nextFrameIfExceedFrameTime();

		// load game layers
		await this.createGameScene();

		await nextFrameIfExceedFrameTime();

		// 5. Wire resize and force initial layout
		this.appInstance.on("resize", () => this.updateLayout());
		this.updateLayout();

		// 6. Game-specific post-scene setup
		await this.onGameReady();
		await nextFrameIfExceedFrameTime();

		// 7. Reveal game, dismiss loader
		this.showGameScene();
	}

	// -- Asset loading

	private async loadPreloadBundle(): Promise<void> {
		// initAssets() is called at module scope in main.tsx — wait for the merged manifest.
		await assetsReady();
		const minLoaderTime = import.meta.env.DEV ? Promise.resolve() : createAbortableDelay(3000).promise;

		await Promise.all([
			Assets.loadBundle("default", (progress: number) => {
				this.setProgress(progress);
			}).then(() => this.setProgress(1)),
			minLoaderTime
		]);
	}

	private setProgress(factor: number): void {
		document.querySelector<HTMLElement>(".progress")?.style.setProperty("--progress-factor", String(factor));
		const percentEl = document.querySelector<HTMLElement>(".loading-percent");
		if (percentEl) {
			percentEl.textContent = `${Math.round(factor * 100)}%`;
		}
	}

	// -- Scene management

	/**
	 * Add a container to the stage, hidden until showGameScene().
	 * Yields a frame before and after — keeps loading screen smooth (nextFrame forest).
	 */
	public async addToScene<T extends Container>(container: T): Promise<T> {
		container.visible = false;
		this.gameContainers.push(container);
		await nextFrame();
		getFanfareBaseSlotApplication().app.stage.addChild(container);
		await nextFrame();
		return container;
	}

	private showGameScene(): void {
		for (const container of this.gameContainers) {
			if (!this.autoRevealExclusions.has(container)) {
				container.visible = true;
			}
		}
		const loader = document.querySelector<HTMLElement>(".loading");
		if (loader) {
			loader.style.transition = "opacity 0.3s ease";
			loader.style.opacity = "0";
			setTimeout(() => loader.classList.add("is-done"), 300);
		}
	}

	public excludeFromAutoReveal(container: Container): void {
		this.autoRevealExclusions.add(container);
	}

	// ── Layout ────────────────────────────────────────────────────────────────

	private updateLayout(): void {
		if (!this.appInstance) return;
		const screen = this.appInstance.app.screen;
		const isDesktop = globalThis.matchMedia?.("(pointer: fine)").matches ?? screen.width >= 1024;

		this.screenSafeArea.resize(screen, isDesktop, screen);
		this.logoArea.resize(screen, isDesktop, screen);
		this.gameArea.resize(screen, isDesktop, screen);
		this.characterArea.resize(screen, isDesktop, screen);

		for (const child of this.appInstance.app.stage.children) {
			if (child instanceof Resizable) {
				child.resize(screen, isDesktop, screen);
			}
		}

		this.fitSlotMachine();
	}

	/**
	 * Scale factor applied after fitting the SlotMachine to GameArea.
	 * Values below 1.0 add breathing room around the reels.
	 * Games can override fitSlotMachine() to use a different value per orientation.
	 */
	/**
	 * How much of the GameArea the slot machine fills.
	 * 1.0 = fills completely, 0.9 = 10% padding around reels.
	 * Override in your game controller to customise per orientation.
	 */
	protected get slotMachineScale(): number {
		const screen = this.appInstance?.app.screen;
		const isPortrait = screen ? screen.height > screen.width : false;
		return isPortrait ? 1 : 0.72; // Padding around the reels, more in landscape to allow for side panels and control bar.
	}

	protected fitSlotMachine(): void {
		if (!ViewStore.getInstance().has("CascadeSlotMachine")) return;
		const sm = ViewStore.getInstance().get("CascadeSlotMachine");
		const area = this.gameArea.getSafeArea();
		const screen = this.appInstance?.app.screen;
		const isPortrait = screen ? screen.height > screen.width : false;

		const scale = Math.min(area.width / sm.reelsWidth, area.height / sm.reelsHeight) * this.slotMachineScale;

		sm.scale.set(scale);

		// In portrait: position slot machine near the top of GameArea
		// rather than centred — leaves space below for breathing room
		const y = isPortrait
			? area.y + area.height / 2 // centred
			: area.y + area.height * 0.42; // centred

		sm.position.set(area.x + area.width / 2, y);
	}

	// -- Abstract

	protected abstract createGameScene(): Promise<void>;
	protected async onGameReady(): Promise<void> {}

	public showError(title: string, message: string): void {
		const wrap = document.querySelector<HTMLDivElement>(".error");
		const h2 = document.querySelector<HTMLHeadingElement>(".error h2");
		const p = document.querySelector<HTMLParagraphElement>(".error p");
		if (wrap) wrap.style.display = "flex";
		if (h2) h2.innerText = title;
		if (p) p.innerText = message;
		document.querySelector(".loading")?.classList.add("is-done");
	}
}
